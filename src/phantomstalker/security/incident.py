def find(query: str) -> Playbook | None:
    q = query.casefold()
    for pb in PLAYBOOKS:
        if q == pb.key or any(alias in q for alias in pb.aliases):
            return pb
    return None


def report(query: str) -> Report:
    if not query.strip():
        r = Report("Що сталося?", summary="Опиши ситуацію або вибери тему: /incident <тема>")
        for pb in PLAYBOOKS:
            r.add(Severity.INFO, f"/incident {pb.key}", pb.title)
        return r
    pb = find(query)
    if pb is None:
        r = Report("План дій при інциденті", summary=query)
        r.add(Severity.HIGH, "Загальні кроки", "1) з чистого пристрою зміни паролі пошти й фінансових сервісів; "
              "2) заверши всі сеанси; 3) увімкни 2FA; 4) збережи докази; 5) попередь контакти")
        r.notes.append("Введи /explain — ШІ складе план саме для твоєї ситуації.")
        return r
    r = Report(f"План дій · {pb.title}", checklist=True)
    for step in pb.now:
        r.add(Severity.CRITICAL, step, "негайно")
    for step in pb.hour:
        r.add(Severity.HIGH, step, "протягом години")
    for step in pb.later:
        r.add(Severity.MEDIUM, step, "потім")
    r.notes.append("Для плану під твою конкретну ситуацію введи /explain і допиши деталі.")
    return r
