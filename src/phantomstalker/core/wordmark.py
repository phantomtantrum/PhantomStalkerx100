def width(rows: list[str]) -> int:
    return max(len(r) for r in rows)


def rows_for(available: int) -> list[str] | None:
    """Найкращий варіант для ширини: в один рядок, у два (як на сайті з шириною 80) або None."""
    if available >= width(ONE_LINE):
        return ONE_LINE
    if available >= max(width(PHANTOM), width(STALKER)):
        return [*PHANTOM, "", *STALKER]
    return None


def render(available: int = 200, style: str = "default") -> Text:
    rows = rows_for(available)
    if rows is None:
        return render_compact(style)
    return Text("\n".join(r.rstrip() for r in rows), style=style, no_wrap=True, overflow="crop")


def render_compact(style: str = "default") -> Text:
    """Для вузьких терміналів: розрядкований напис в один рядок."""
    return Text(" ".join(NAME).replace("   ", "  ·  "), style=f"bold {style}")
